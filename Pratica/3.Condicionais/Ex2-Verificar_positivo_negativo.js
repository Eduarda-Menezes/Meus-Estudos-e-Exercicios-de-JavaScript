/*Peça um número e informe se ele é:

positivo;
negativo;
ou igual a zero. */

let num = Number(prompt("Digite seu numero: "))

if(num > 0){
  alert("Seu numero é positivo!");
} else if (num = 0){
  alert("Seu numero é zero!");
} else{
  alert("Seu numero é negativo!");
}